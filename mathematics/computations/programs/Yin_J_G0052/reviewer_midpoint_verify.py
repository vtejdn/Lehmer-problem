"""Independent C819 verification at the fixed height48/time256 scope.

No author mathematical code is imported.  Integer slicing enumerates the
outward-strip superset; depth-first searches use original chronological states,
and predecessor-gather evolution counts returns and killed first returns.
The author JSON is read only after independent data have been computed.
"""
from fractions import Fraction as Q
from itertools import product
from pathlib import Path
import argparse
import json

HERE = Path(__file__).resolve().parent
ROOT = next(p for p in HERE.parents if (p / 'repository/config.json').is_file())
OUTPUT = ROOT / 'mathematics/computations/outputs' / HERE.name
H, LIMIT, CAP, SCALE = 48, 256, 100000, 10**6
TIMES = (16, 32, 64, 128)
ZERO = (0, 0, 0, 0)


def floor(x):
    return x.numerator // x.denominator


def ceil(x):
    return -floor(-x)


def ratio(x):
    return {'numerator': x.numerator, 'denominator': x.denominator}


def to_original(q):
    return tuple(-q[j] + sum(q[j + 1:]) for j in range(4))


def to_quotient(a):
    q = [0] * 4
    for j in range(3, -1, -1):
        q[j] = sum(q[j + 1:]) - a[j]
    return tuple(q)


def next_original(a, digit):
    b, c, d, e = a
    return (digit - e, b + e, c + e, d + e)


def previous_original(a, digit):
    b, c, d, e = a
    return (b + c - digit, b + d - digit, b + e - digit, digit - b)


def allowed_states():
    lo, hi = Q(861, 500), Q(1723, 1000)
    def polynomial(x):
        return x**4 - x**3 - x**2 - x + 1
    assert polynomial(lo) < 0 < polynomial(hi)
    root_lower = Q(721, 200)
    assert root_lower**2 < 13
    assert (hi**2 + 1/lo) / ((lo-1)*root_lower*(lo-1/lo)) < Q(6, 5)
    assert 4 / (13*(1+root_lower)/2) < Q(11, 30)**2
    assert Q(6, 5) + Q(11, 30)*(LIMIT//2) < H + 1
    strips = []
    for low, high, bound in ((lo, hi, 1/(lo-1)), (1/hi, 1/lo, lo/(lo-1))):
        functions = (lambda t: -1/t, lambda t: t*t-t-1, lambda t: t-1)
        intervals = tuple((floor(f(low)*SCALE), ceil(f(high)*SCALE)) for f in functions)
        strips.append((intervals, ceil(bound*SCALE)))
    result = set()
    for prefix in product(range(-H, H+1), repeat=3):
        lower, upper = -H, H
        for intervals, bound in strips:
            left = sum(min(q*a, q*b) for q, (a, b) in zip(prefix, intervals))
            right = sum(max(q*a, q*b) for q, (a, b) in zip(prefix, intervals))
            lower = max(lower, -((bound + right)//SCALE))
            upper = min(upper, (bound - left)//SCALE)
        for last in range(lower, upper+1):
            q = prefix + (last,)
            a = to_original(q)
            assert to_quotient(a) == q
            result.add(a)
    return result


def reachable(universe, transition):
    found, stack = {ZERO}, [ZERO]
    while stack:
        state = stack.pop()
        for digit in (-1, 0, 1):
            target = transition(state, digit)
            if target in universe and target not in found:
                if len(found) >= CAP:
                    raise RuntimeError('Reached-state cap hit; incomplete')
                found.add(target)
                stack.append(target)
    return found


def field_mul(x, y):
    return (x[0]*y[0] + 13*x[1]*y[1], x[0]*y[1] + x[1]*y[0])


def norm_mark(a):
    # z^l+z^-l is generated by the recurrence V_(l+1)=u V_l-V_(l-1).
    u = (Q(1, 2), Q(-1, 2))
    terms = [(Q(2), Q(0)), u]
    for k in (2, 3):
        z = field_mul(u, terms[-1])
        terms.append(tuple(z[j] - terms[-2][j] for j in (0, 1)))
    coefficients = [Q(sum(x*x for x in a)), Q(0)]
    for k in (1, 2, 3):
        correlation = sum(a[i]*a[i+k] for i in range(4-k))
        for j in (0, 1):
            coefficients[j] += correlation * terms[k][j]
    values = tuple(2*x for x in coefficients)
    assert all(x.denominator == 1 for x in values)
    return tuple(int(x) for x in values)


def calculate():
    universe = allowed_states()
    # Original forward reachability equals quotient return reachability;
    # original backward reachability equals the author's quotient forward set.
    forward_set = reachable(universe, next_original)
    backward_set = reachable(universe, previous_original)
    states = sorted(forward_set & backward_set)
    index = {a: j for j, a in enumerate(states)}
    zero = index[ZERO]
    incoming, outgoing = [], []
    for a in states:
        incoming.append([(index[b], 2 if digit == 0 else 1)
                         for digit in (-1, 0, 1)
                         if (b := previous_original(a, digit)) in index])
        outgoing.append([(index[b], 2 if digit == 0 else 1)
                         for digit in (-1, 0, 1)
                         if (b := next_original(a, digit)) in index])
    current = [int(j == zero) for j in range(len(states))]
    killed = current.copy()
    returns, firsts, saved = [1], [0], {}
    for t in range(1, LIMIT+1):
        current = [sum(current[j]*w for j, w in row) for row in incoming]
        killed = [sum(killed[j]*w for j, w in row) for row in incoming]
        returns.append(current[zero])
        firsts.append(killed[zero])
        killed[zero] = 0
        assert returns[t] == sum(firsts[j]*returns[t-j] for j in range(1, t+1))
        if t in TIMES:
            saved[t] = current.copy()
    terminal = [int(j == zero) for j in range(len(states))]
    marks = [norm_mark(a) for a in states]
    sqrt_lo, sqrt_hi = Q(3605551275463989, 10**15), Q(3605551275463990, 10**15)
    assert sqrt_lo**2 < 13 < sqrt_hi**2
    rows = []
    for t in range(1, max(TIMES)+1):
        terminal = [sum(terminal[j]*w for j, w in row) for row in outgoing]
        assert terminal[zero] == returns[t]
        if t not in TIMES:
            continue
        weights = [x*y for x, y in zip(saved[t], terminal)]
        total = sum(weights)
        assert total == returns[2*t]
        sums = tuple(sum(w*mark[k] for w, mark in zip(weights, marks)) for k in (0, 1))
        a, b = (Q(v, 2*total) for v in sums)
        low, high = sorted((a+b*sqrt_lo, a+b*sqrt_hi))
        overlap = Q(total, returns[t]**2)
        assert Q(floor(overlap*SCALE), SCALE) < overlap < Q(floor(overlap*SCALE)+1, SCALE)
        assert Q(floor(low*SCALE/t), SCALE) < low/t < high/t < Q(ceil(high*SCALE/t), SCALE)
        if t in (64, 128):
            assert low/t > Q(1, 5)
        quotient_means = [sum(w*to_quotient(s)[j] for w, s in zip(weights, states)) for j in range(4)]
        assert quotient_means == [0]*4
        rows.append({'midpoint_time': t, 'positive_midpoint_states': sum(w > 0 for w in weights),
                     'complete_bridge_weight': total, 'moment_integer_A_sum': sums[0],
                     'moment_integer_B_sum': sums[1], 'overlap_D_n': ratio(Q(total, returns[t]**2)),
                     'moment_lower': ratio(low), 'moment_upper': ratio(high),
                     'weighted_quotient_coordinate_means': quotient_means,
                     'overlap_rational_enclosure': [ratio(Q(floor(Q(total, returns[t]**2)*SCALE), SCALE)),
                         ratio(Q(floor(Q(total, returns[t]**2)*SCALE)+1, SCALE))],
                     'scaled_moment_rational_enclosure': [ratio(Q(floor(low*SCALE/t), SCALE)),
                         ratio(Q(ceil(high*SCALE/t), SCALE))]})
    lo, hi = Q(861, 500), Q(1723, 1000)
    p = [Q(w, 4**t) for t, w in enumerate(returns)]
    expected = {16: Q(5339, 2**27), 32: Q(504250923, 2**57),
                64: Q(121338835637214357477, 2**121),
                128: Q(241348810511898190541699791270635467354265589, 2**253),
                256: Q(264543412341747108848944040326875358997077741567393090275411759418849446982212078897310231, 2**504)}
    assert all(p[t] == value for t, value in expected.items())
    assert all(p[t]*hi**t < 1 for t in range(1, LIMIT+1))
    first_low = sum(Q(firsts[t], 4**t)*lo**t for t in range(1, LIMIT+1))
    first_high = sum(Q(firsts[t], 4**t)*hi**t for t in range(1, LIMIT+1))
    assert Q(948616, SCALE) < first_low < first_high < Q(950835, SCALE) < 1
    assert 16*lo/(lo-1)**2 < 53
    assert Q(7, 2)**2 < 13
    assert 212*(Q(LIMIT, 2)+Q(2, 3)) < Q(9, 16)*LIMIT**2
    assert 1+Q(106, 3) < Q(LIMIT, 4)
    certificate = 55*LIMIT*p[LIMIT]*Q(1687, 1000)**LIMIT
    assert certificate < 1
    return {'scope': {'height': H, 'complete_return_times': [1, LIMIT], 'midpoint_times': list(TIMES),
                      'reached_state_cap': CAP, 'original_digit_weights': [1, 2, 1]},
            'graph': {'allowed_lattice_points': len(universe), 'original_forward_reached': len(forward_set),
                      'quotient_forward_reached': len(backward_set), 'returning_graph_states': len(states),
                      'retained_edges': sum(map(len, outgoing))},
            'complete_return_integer_weights': returns, 'complete_first_return_integer_weights': firsts,
            'midpoints': rows, 'selected_complete_returns': {str(t): ratio(p[t]) for t in (*TIMES, LIMIT)},
            'partial_first_return_at_beta_lower_bracket': ratio(first_low),
            'partial_first_return_at_beta_upper_bracket': ratio(first_high),
            'radius_certificate_product': ratio(certificate), 'all_times_fail_strict_pressure_crossing': True}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--author-input', type=Path, default=OUTPUT/'midpoint_continuation.json')
    parser.add_argument('--output', type=Path, default=OUTPUT/'reviewer_midpoint_result.json')
    args = parser.parse_args()
    result = calculate()
    author = json.loads(args.author_input.read_text(encoding='utf-8'))
    assert author['scope']['complete_return_times'] == [1, LIMIT]
    assert author['scope']['midpoint_times'] == list(TIMES)
    assert author['scope']['deterministic_complete_height'] == H
    assert author['scope']['state_cap'] == CAP
    assert author['scope']['digit_integer_weights'] == {'-1': 1, '0': 2, '1': 1}
    assert author['scope']['digit_denominator'] == 4
    for key in ('complete_return_integer_weights', 'complete_first_return_integer_weights',
                'selected_complete_returns', 'partial_first_return_at_beta_lower_bracket',
                'partial_first_return_at_beta_upper_bracket', 'radius_certificate_product',
                'all_times_fail_strict_pressure_crossing'):
        assert result[key] == author[key], key
    for independent, recorded in zip(result['midpoints'], author['midpoints'], strict=True):
        for key, value in independent.items():
            assert value == recorded[key], (independent['midpoint_time'], key)
    for ours, theirs in (('quotient_forward_reached', 'forward_reached_states'),
                        ('returning_graph_states', 'returning_graph_states'), ('retained_edges', 'retained_edges')):
        assert result['graph'][ours] == author['graph'][theirs]
    result['comparison'] = 'Exact agreement on complete lists, selected probabilities, all four midpoint marks and intervals, graph counts, both pressure tests and radius certificate.'
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temp = args.output.with_suffix('.json.tmp')
    temp.write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8')
    temp.replace(args.output)
    print(json.dumps({'graph': result['graph'], 'comparison': result['comparison']}, indent=2))


if __name__ == '__main__':
    main()
